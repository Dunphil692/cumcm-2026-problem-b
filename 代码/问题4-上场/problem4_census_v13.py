import math

INNER_RING_A = 900.0   # 内环 6 点，0° 起 60° 间隔
INNER_RING_B = 1350.0  # 中环 6 点，30° 起 60° 间隔
OUTER_R = 1900.0       # 外环半径（略大于目标圆，出圆合法）
OUTER_OFFSET_DEG = 15.0  # 外环 12 点，15° 起 30° 间隔


def inner_stops() -> list[tuple[float, float]]:
    stops = [(0.0, 0.0)]
    for index in range(6):
        angle = math.radians(index * 60.0)
        stops.append(
            (INNER_RING_A * math.cos(angle), INNER_RING_A * math.sin(angle))
        )
    for index in range(6):
        angle = math.radians(30.0 + index * 60.0)
        stops.append(
            (INNER_RING_B * math.cos(angle), INNER_RING_B * math.sin(angle))
        )
    return stops


def outer_stops() -> list[tuple[float, float]]:
    return [
        (
            OUTER_R * math.cos(math.radians(OUTER_OFFSET_DEG + index * 30.0)),
            OUTER_R * math.sin(math.radians(OUTER_OFFSET_DEG + index * 30.0)),
        )
        for index in range(12)
    ]


